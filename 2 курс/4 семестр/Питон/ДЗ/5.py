import math


def main(z, x):
    sum_v = 0
    n = len(z)
    for i in range(1, n+1):
        term = 89*(x[i-1])**3 - (x[n-i])**2 - (77*z[n-i])
        sum_v += math.sin(term)**6
    return 33 * sum_v


